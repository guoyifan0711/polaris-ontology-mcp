import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {request as httpRequest} from 'node:http';
import {createSessionRelay, SITE_ORIGIN} from './session-relay.mjs';

const {tools} = JSON.parse(await readFile(new URL('../tool-catalog.json', import.meta.url)));
let opened = 0;
let schemaUpdates = 0;
const cloudTools = structuredClone(tools);
cloudTools[0].inputSchema.properties = {test_marker: {type: 'string'}};
const relay = await createSessionRelay({tools, timeoutMs: 800, pollMs: 35, open: async () => { opened++; }, onToolsChanged: () => { schemaUpdates++; }});
const target = 'http://127.0.0.1:' + relay.port;
const key = new URLSearchParams(relay.connectUrl.split('#')[1]).get('key');
const headers = {Origin: SITE_ORIGIN, Authorization: 'Bearer ' + key, 'Content-Type': 'application/json'};
const call = (path, body, overrides = {}) => fetch(target + path, {method: body === undefined ? 'GET' : 'POST', headers: {...headers, ...overrides}, body: body === undefined ? undefined : JSON.stringify(body)});
const rpc = id => ({jsonrpc: '2.0', id, method: 'tools/call', params: {name: 'polaris_source_status', arguments: {}}});
try {
  assert.equal((await fetch(target + '/status')).status, 403);
  assert.equal((await call('/status', undefined, {Origin: 'https://attacker.example'})).status, 403);
  assert.equal((await call('/status', undefined, {Authorization: 'Bearer wrong'})).status, 401);
  const wrongHost = await new Promise((resolve, reject) => {
    const request = httpRequest(target + '/status', {headers: {...headers, Host: 'attacker.example'}}, response => { response.resume(); resolve(response.statusCode); });
    request.once('error', reject);
    request.end();
  });
  assert.equal(wrongHost, 403);
  const preflight = await fetch(target + '/poll', {method: 'OPTIONS', headers: {Origin: SITE_ORIGIN, 'Access-Control-Request-Private-Network': 'true'}});
  assert.equal(preflight.status, 204);
  assert.equal(preflight.headers.get('access-control-allow-origin'), SITE_ORIGIN);
  assert.equal(preflight.headers.get('access-control-allow-private-network'), 'true');
  await assert.rejects(relay.call(rpc(1)), /连接本机 Codex/);
  await assert.rejects(relay.call(rpc(2)), /连接本机 Codex/);
  assert.equal(opened, 1);
  assert.equal((await call('/ready', {email: 'viewer@example.test', tools: []})).status, 400);
  assert.equal((await call('/ready', {email: 'viewer@example.test', subject: 'viewer-subject', tools: cloudTools})).status, 200);
  assert.equal(schemaUpdates, 1);
  assert.deepEqual(relay.tools, cloudTools);
  assert.equal(relay.status().connected, true);
  assert.equal((await call('/ready', {email: 'other@example.test', tools})).status, 409);
  const request = relay.call(rpc(3));
  const {jobs} = await (await call('/poll')).json();
  assert.equal(jobs.length, 1);
  assert.deepEqual(jobs[0].rpc, rpc(3));
  assert.equal((await call('/result', {id: jobs[0].id, status: 200, body: {jsonrpc: '2.0', id: 999, result: {}}})).status, 400);
  const cloud = {jsonrpc: '2.0', id: 3, result: {structuredContent: {source_snapshot: 'test-source'}, content: [{type: 'text', text: 'unchanged'}]}};
  assert.equal((await call('/result', {id: jobs[0].id, status: 200, body: cloud})).status, 200);
  assert.deepEqual(await request, cloud);
  assert.equal((await call('/result', {id: jobs[0].id, status: 200, body: cloud})).status, 400);
  await assert.rejects(relay.call({...rpc(4), params: {name: 'delete_data'}}), /只读范围/);
  await assert.rejects(relay.call({...rpc(4), params: {name: 'polaris_query', arguments: {q: 'a'.repeat(70000)}}}), /参数过大/);
  const waiting = relay.call(rpc(5));
  const rejection = assert.rejects(waiting, /Site 已拒绝访问/);
  const next = await (await call('/poll')).json();
  await call('/result', {id: next.jobs[0].id, status: 403, body: {jsonrpc: '2.0', id: 5, error: {code: -32001, message: 'denied'}}});
  await rejection;
  assert.equal(relay.status().connected, false);
  await call('/ready', {email: 'viewer@example.test', tools});
  await assert.rejects(relay.call(rpc(6)), /时限内/);
  assert.equal(relay.status().pending, 0);
  const inflight = [7,8,9,10].map(id => relay.call(rpc(id)));
  const outcomes = inflight.map(p => p.catch(error => error));
  await assert.rejects(relay.call(rpc(11)), /查询较多/);
  await call('/disconnect', {});
  for (const result of await Promise.all(outcomes)) assert.match(result.message, /已断开/);
  assert.equal(relay.status().pending, 0);
  assert.equal((await call('/poll')).status, 409);
  console.log('Relay origin, host, token, pairing, concurrency, timeout, denial, replay and byte-identical response checks passed.');
} finally { await relay.close(); }
